import { PracticeExercise } from '../types/quest';

interface RawSpec {
  title: string;
  theme: string;
  instructions: string;
  starter: string;
  input: string;
  expected: string;
  solution: string;
  hints: [string, string, string];
  criteria: string[];
  explanation: string;
}

function buildLessonSet(lessonId: number, specs: RawSpec[]): PracticeExercise[] {
  const categories: PracticeExercise['category'][] = [
    'warmup',
    'warmup',
    'warmup',
    'predict',
    'predict',
    'predict',
    'completion',
    'completion',
    'debug',
    'debug',
    'independent',
    'boss',
  ];
  const difficulties: PracticeExercise['difficulty'][] = [
    'Level 1: Warm-up',
    'Level 1: Warm-up',
    'Level 1: Warm-up',
    'Level 2: Core',
    'Level 2: Core',
    'Level 2: Core',
    'Level 2: Core',
    'Level 2: Core',
    'Level 3: Independent',
    'Level 3: Independent',
    'Level 3: Independent',
    'Level 4: Boss',
  ];
  const xpMap = [15, 15, 15, 20, 20, 20, 25, 25, 30, 30, 40, 60];

  return specs.map((s, idx) => ({
    id: `C${String(lessonId).padStart(2, '0')}-E${String(idx + 1).padStart(2, '0')}`,
    lessonId,
    category: categories[idx],
    title: s.title,
    difficulty: difficulties[idx],
    contextTheme: s.theme,
    instructions: s.instructions,
    starterCode: s.starter,
    inputExample: s.input,
    expectedOutput: s.expected,
    teacherSolution: s.solution,
    hints: s.hints,
    markingCriteria: s.criteria,
    explanation: s.explanation,
    xpReward: xpMap[idx],
  }));
}

